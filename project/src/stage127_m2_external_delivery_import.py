# --------------------------------------------------------------------------- #
# Small helpers
# --------------------------------------------------------------------------- #

def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _read_csv(data: bytes) -> list[dict[str, str]]:
    text = data.decode("utf-8-sig")
    return list(csv.DictReader(io.StringIO(text)))


def _num(value: str) -> float | None:
    v = (value or "").strip()
    if v == "":
        return None
    return float(v)


def deven_to_iso(deven: int) -> str:
    s = str(int(deven))
    if len(s) != 8:
        raise ImportFail(f"malformed dEven: {deven}")
    return f"{s[0:4]}-{s[4:6]}-{s[6:8]}"


def parse_adjusted_records(text: str) -> dict[str, float]:
    """Parse a Financial.aspx ``t=ph&a=1`` payload into {iso_date: pc}.

    Parsed independently of the external extraction code so a defect there
    cannot propagate silently into the Gate.
    """
    out: dict[str, float] = {}
    for part in text.strip().split(";"):
        if not part.strip():
            continue
        fields = part.split(",")
        if len(fields) < ADJUSTED_FIELD_COUNT:
            raise ImportFail(f"malformed adjusted record: {part!r}")
        iso = deven_to_iso(int(fields[0]))
        if iso in out:
            raise ImportFail(f"duplicate adjusted date {iso}")
        out[iso] = float(fields[ADJUSTED_PC_INDEX])
    return out


def parse_adjusted_volumes(text: str) -> dict[str, float]:
    """Volume column of the adjusted payload, used only as a join cross-check."""
    out: dict[str, float] = {}
    for part in text.strip().split(";"):
        if not part.strip():
            continue
        fields = part.split(",")
        if len(fields) < ADJUSTED_FIELD_COUNT:
            continue
        out[deven_to_iso(int(fields[0]))] = float(fields[ADJUSTED_VOLUME_INDEX])
    return out


