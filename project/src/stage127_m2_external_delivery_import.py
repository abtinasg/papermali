class ExternalDelivery:
    """Read-only handle over the external ZIP. Nothing is ever written back."""

    def __init__(self, zip_path: str, *, expected_sha256: str | None = None,
                 expected_size: int | None = None) -> None:
        self.zip_path = os.path.abspath(zip_path)
        if not os.path.isfile(self.zip_path):
            raise ImportFail(f"external bundle not found: {self.zip_path}")

        self.size_bytes = os.path.getsize(self.zip_path)
        self.sha256 = sha256_file(self.zip_path)

        want_sha = BUNDLE_SHA256 if expected_sha256 is None else expected_sha256
        want_size = BUNDLE_SIZE_BYTES if expected_size is None else expected_size

        if self.size_bytes != want_size:
            raise ImportFail(
                f"external bundle size mismatch: expected {want_size}, "
                f"got {self.size_bytes}"
            )
        if self.sha256 != want_sha:
            raise ImportFail(
                f"external bundle SHA256 mismatch: expected {want_sha}, "
                f"got {self.sha256}"
            )

        self._zf = zipfile.ZipFile(self.zip_path)
        self.names = tuple(self._zf.namelist())

        for name in self.names:
            if name.startswith(FORBIDDEN_PREFIX):
                raise ImportFail(
                    "delivery contains raw_full_escrow; the full-history escrow "
                    "must remain outside the ingested evidence bundle"
                )
        for required in REQUIRED_BUNDLE_MEMBERS:
            if required not in self.names:
                raise ImportFail(f"delivery is missing required member: {required}")

    def close(self) -> None:
        self._zf.close()

    def __enter__(self) -> "ExternalDelivery":
        return self

    def __exit__(self, *exc: Any) -> None:
        self.close()

    def read(self, member: str) -> bytes:
        try:
            return self._zf.read(member)
        except KeyError as exc:  # pragma: no cover - defensive
            raise ImportFail(f"missing bundle member: {member}") from exc

    def read_text(self, member: str) -> str:
        return self.read(member).decode("utf-8-sig")

    def read_csv(self, member: str) -> list[dict[str, str]]:
        return _read_csv(self.read(member))

    def restricted_files(self) -> list[str]:
        prefix = f"{ROOT}/raw_restricted/"
        return sorted(
            n for n in self.names
            if n.startswith(prefix) and not n.endswith("/")
        )


